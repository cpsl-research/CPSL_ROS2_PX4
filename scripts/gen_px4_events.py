#!/usr/bin/env python3
"""Generate px4_controller/px4_event_table.py from a PX4 build's all_events.json.

The table lets the node turn a MAVLink EVENT id into text (e.g. 133277 =
"Arming denied: Resolve system health failures first") without a firmware
build tree at run time. Regenerate whenever firmware/versions.json moves:

    python3 scripts/gen_px4_events.py \
        firmware/out/px4_fmu-v6x_default/events/all_events.json

The output path defaults to src/px4_controller/px4_controller/px4_event_table.py.
"""
import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, '..', 'src', 'px4_controller', 'px4_controller',
                           'px4_event_table.py')


def build(doc):
    """Return (events, enums): events[id] = (name, message, ((argname, type), ...))."""
    events, enums = {}, {}
    for comp in doc['components'].values():
        for name, enum in comp.get('enums', {}).items():
            enums[name] = (enum.get('type', 'uint8_t'), bool(enum.get('is_bitfield')),
                           {int(v): e['name'] for v, e in enum['entries'].items()})
        for group in comp['event_groups'].values():
            for eid, ev in group['events'].items():
                args = tuple((a['name'], a['type'].replace('px4::', ''))
                             for a in ev.get('arguments', []))
                events[int(eid)] = (ev['name'], ev['message'], args)
    return events, enums


def render(events, enums, src_sha):
    out = ['"""PX4 event id -> text table. GENERATED by scripts/gen_px4_events.py; do not edit.',
           '',
           'Source: all_events.json of the pinned firmware build, sha256 %s.' % src_sha,
           '"""', '',
           '# id: (name, message with {n} placeholders, ((arg name, type), ...))',
           'EVENTS = {']
    for eid in sorted(events):
        out.append('    %d: %r,' % (eid, events[eid]))
    out += ['}', '', '# enum type: (underlying int type, is_bitfield, {value: name})', 'ENUMS = {']
    for name in sorted(enums):
        out.append('    %r: %r,' % (name, enums[name]))
    out += ['}', '']
    return '\n'.join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('all_events_json')
    ap.add_argument('--out', default=DEFAULT_OUT)
    a = ap.parse_args(argv)
    raw = open(a.all_events_json, 'rb').read()
    events, enums = build(json.loads(raw))
    with open(a.out, 'w') as f:
        f.write(render(events, enums, hashlib.sha256(raw).hexdigest()))
    print('wrote %d events, %d enums to %s' % (len(events), len(enums), os.path.normpath(a.out)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
